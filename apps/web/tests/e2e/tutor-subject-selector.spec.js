import { test, expect } from '@playwright/test';
import { resetDemo, login } from './demoHelpers.js';

test('Tutor subject selector stays compact and preserves multi selection', async ({ page }) => {
  await resetDemo(page);
  await page.setViewportSize({ width: 1440, height: 900 });
  await login(page, 'giabao', '/tutor/profile');
  const search = page.getByRole('combobox', { name: 'Tìm chuyên môn' });
  const form = page.locator('.flow-form');
  const before = await form.evaluate((element) => element.getBoundingClientRect().height);
  await search.focus();
  await expect(page.getByRole('listbox', { name: 'Gợi ý chuyên môn' }).getByRole('option')).toHaveCount(7);
  expect(await form.evaluate((element) => element.getBoundingClientRect().height)).toBe(before);
  await expect(search).toHaveAttribute('placeholder', 'Tìm môn học hoặc kỹ năng...');
  await search.fill('Toán');
  await expect(page.getByRole('option', { name: /Toán/ }).first()).toBeVisible();
  await page.screenshot({ path: 'test-results/tutor-subject-selector-dropdown-light.png' });
  await page.getByRole('button', { name: 'Xóa từ khóa' }).click();
  await expect(search).toHaveValue('');
  await search.fill('AI');
  await expect(page.locator('#profile-subject-technology-ai')).toBeVisible();
  await expect(page.getByRole('option', { name: /Machine Learning/ })).toBeVisible();
  await expect(page.getByRole('option', { name: /Generative AI/ })).toBeVisible();
  await page.locator('#profile-subject-technology-ai').click();
  await expect(page.locator('.profile-subjects__tags')).toContainText('Trí tuệ nhân tạo (AI)');
  await expect(page.locator('.profile-subjects__tags')).not.toContainText('Machine Learning');
  await search.fill('AI');
  await expect(page.locator('#profile-subject-technology-ai')).toHaveAttribute('aria-selected', 'true');
  await expect(page.locator('#profile-subject-technology-ai svg')).toBeVisible();
  await page.getByRole('option', { name: /Machine Learning/ }).click();
  await search.fill('mĩ thuật');
  await expect(page.getByRole('option', { name: /Vẽ \/ Hội họa/ })).toBeVisible();
  await search.press('Escape');
  await expect(page.getByRole('listbox', { name: 'Gợi ý chuyên môn' })).toHaveCount(0);
  await search.click();
  await expect(page.getByRole('listbox', { name: 'Gợi ý chuyên môn' })).toBeVisible();
  await search.fill('Thiết kế Canva nâng cao');
  await expect(page.getByText('Không tìm thấy chuyên môn phù hợp.')).toBeVisible();
  await page.getByRole('button', { name: '+ Đề xuất chuyên môn mới' }).click();
  await expect(page.getByRole('dialog', { name: 'Đề xuất chuyên môn mới' })).toBeVisible();
  await page.getByRole('button', { name: 'Hủy' }).click();
  await page.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click();
  await page.reload();
  await expect(page.locator('.profile-subjects__tags')).toContainText('Machine Learning');
  await page.getByRole('button', { name: 'Bỏ Trí tuệ nhân tạo (AI)' }).click();
  await expect(page.locator('.profile-subjects__tags')).not.toContainText('Trí tuệ nhân tạo (AI)');
  await expect(page.locator('.profile-subjects__tags')).toContainText('Machine Learning');
  await page.screenshot({ path: 'test-results/tutor-subject-selector-light.png' });
});

